export const LANGS: Record<string, { name: string; dict: Dict }> = {
  en: { name: 'English', dict: en },
  fr: { name: 'Français', dict: fr },
  pt: { name: 'Português', dict: pt },
  es: { name: 'Español', dict: es },
  de: { name: 'Deutsch', dict: de },
  it: { name: 'Italiano', dict: it },
};

/** More languages can be added at run time (see locales.ts). */
export function addLanguage(code: string, name: string, dict: Dict): void {
  LANGS[code] = { name, dict };
}

let current = 'en';

export function detectLanguage(): string {
  const list = (typeof navigator !== 'undefined' && (navigator.languages || [navigator.language])) || ['en'];
  for (const tag of list) {
    if (!tag) continue;
    const lower = tag.toLowerCase();
    if (LANGS[lower]) return lower;
    const base = lower.split('-')[0];
    if (LANGS[base]) return base;
  }
  return 'en';
}

export function setLanguage(code: string): void {
  current = LANGS[code] ? code : 'en';
  if (typeof document !== 'undefined') {
    document.documentElement.lang = current;
    document.documentElement.dir = current === 'ar' || current === 'he' || current === 'fa' ? 'rtl' : 'ltr';
  }
}

export function language(): string {
  return current;
}

export function t(key: string, vars?: Record<string, string | number>): string {
  let s = LANGS[current].dict[key] ?? en[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]));
  return s;
}

